/// Mixes one block of 64 bytes into the state.
#[allow(clippy::many_single_char_names, reason = "the names of FIPS 180-4")]
fn block(zustand: &mut [u32; 8], bytes: &[u8; 64]) {
    let mut w = [0u32; 64];
    for (wort, vier) in w.iter_mut().zip(bytes.as_chunks::<4>().0) {
        *wort = u32::from_be_bytes(*vier);
    }
    for t in 16..64 {
        let s0 = w[t - 15].rotate_right(7) ^ w[t - 15].rotate_right(18) ^ (w[t - 15] >> 3);
        let s1 = w[t - 2].rotate_right(17) ^ w[t - 2].rotate_right(19) ^ (w[t - 2] >> 10);
        w[t] = w[t - 16]
            .wrapping_add(s0)
            .wrapping_add(w[t - 7])
            .wrapping_add(s1);
    }
    let [mut a, mut b, mut c, mut d, mut e, mut f, mut g, mut h] = *zustand;
    for (kt, wt) in K.iter().zip(w) {
        let s1 = e.rotate_right(6) ^ e.rotate_right(11) ^ e.rotate_right(25);
        let ch = g ^ (e & (f ^ g));
        let t1 = h
            .wrapping_add(s1)
            .wrapping_add(ch)
            .wrapping_add(*kt)
            .wrapping_add(wt);
        let s0 = a.rotate_right(2) ^ a.rotate_right(13) ^ a.rotate_right(22);
        let maj = a ^ ((a ^ b) & (a ^ c));
        let t2 = s0.wrapping_add(maj);
        h = g;
        g = f;
        f = e;
        e = d.wrapping_add(t1);
        d = c;
        c = b;
        b = a;
        a = t1.wrapping_add(t2);
    }
    for (z, neu) in zustand.iter_mut().zip([a, b, c, d, e, f, g, h]) {
        *z = z.wrapping_add(neu);
    }
}

/// The SHA-256 digest of `daten` as 64 lower-case hex digits.
#[must_use]
pub fn sha256_hex(daten: &[u8]) -> String {
    let mut zustand = H0;
    let (bloecke, rest) = daten.as_chunks::<64>();
    for b in bloecke {
        block(&mut zustand, b);
    }
    // Padding: 0x80, zeros up to 56 mod 64, the length in bits as 64-bit big endian.
    let mut ende = Vec::with_capacity(128);
    ende.extend_from_slice(rest);
    ende.push(0x80);
    ende.resize(rest.len() + 1 + (119 - rest.len()) % 64, 0);
    let bits = (daten.len() as u64).wrapping_mul(8);
    ende.extend_from_slice(&bits.to_be_bytes());
    for b in ende.as_chunks::<64>().0 {
        block(&mut zustand, b);
    }
    let mut hex = String::with_capacity(64);
    for wort in zustand {
        for byte in wort.to_be_bytes() {
            hex.push(char::from(b"0123456789abcdef"[usize::from(byte >> 4)]));
            hex.push(char::from(b"0123456789abcdef"[usize::from(byte & 15)]));
        }
    }
    hex
}

#[cfg(test)]
mod tests {
    use super::sha256_hex;

    #[test]
    fn fips_vectors() {
        assert_eq!(
            sha256_hex(b""),
            "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
        );
        assert_eq!(
            sha256_hex(b"abc"),
            "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
        );
        assert_eq!(
            sha256_hex(b"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq"),
            "248d6a61d20638b8e5c026930c3e6039a33ce45964ff2167f6ecedd419db06c1"
        );
        assert_eq!(
            sha256_hex(
                b"abcdefghbcdefghicdefghijdefghijkefghijklfghijklmghijklmnhijklmnoijklmnopjklmnopqklmnopqrlmnopqrsmnopqrstnopqrstu"
            ),
            "cf5b16a778af8380036ce59e7b0492370b249b11e8f07a51afac45037afee9d1"
        );
    }

    #[test]
    fn one_million_a() {
        let daten = vec![b'a'; 1_000_000];
        assert_eq!(
            sha256_hex(&daten),
            "cdc76e5c9914fb9281a1c7e284d73e67f1809a48a497200e046d39ccc7112cd0"
        );
    }

    #[test]
    fn padding_edges() {
        // Lengths around the block and the length field: 55, 56, 63, 64, 65 bytes (references from python3 hashlib).
        let erwartet = [
            (
                55,
                "9f4390f8d30c2dd92ec9f095b65e2b9ae9b0a925a5258e241c9f1e910f734318",
            ),
            (
                56,
                "b35439a4ac6f0948b6d6f9e3c6af0f5f590ce20f1bde7090ef7970686ec6738a",
            ),
            (
                63,
                "7d3e74a05d7db15bce4ad9ec0658ea98e3f06eeecf16b4c6fff2da457ddc2f34",
            ),
            (
                64,
                "ffe054fe7ae0cb6dc65c3af9b61d5209f439851db43d0ba5997337df154668eb",
            ),
            (
                65,
                "635361c48bb9eab14198e76ea8ab7f1a41685d6ad62aa9146d301d4f17eb0ae0",
            ),
        ];
        for (n, hex) in erwartet {
            assert_eq!(sha256_hex(&vec![b'a'; n]), hex, "length {n}");
        }
    }
}
