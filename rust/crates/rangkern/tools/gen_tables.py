"""Generates src/tables.rs: the character classes of Python's `str` for the Unicode version of the interpreter.

Usage: python gen_tables.py > ../src/tables.rs

`str.isalpha()` is the category L (Lu, Ll, Lt, Lm, Lo). Python's `\\w` for text patterns is
`str.isalnum()` or `_`, and `isalnum` is isalpha, isdecimal, isdigit or isnumeric. Rust's
`char::is_alphabetic` and the `\\w` of the regex crate are other sets (combining marks, letter numbers),
so the two tables are generated, not derived.
"""
import sys
import unicodedata


def ranges(pred):
    out = []
    start = prev = None
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            ok = False
        else:
            ok = pred(chr(cp))
        if ok:
            if start is None:
                start = cp
            prev = cp
        elif start is not None:
            out.append((start, prev))
            start = None
    if start is not None:
        out.append((start, prev))
    return out


def emit(name, doc, table):
    print(f"/// {doc}")
    print(f"pub const {name}: &[(u32, u32)] = &[")
    for lo, hi in table:
        print(f"    (0x{lo:X}, 0x{hi:X}),")
    print("];")
    print()


print("//! Generated by `tools/gen_tables.py`; do not edit.")
print(f"//! Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}.")
print()
emit("ALPHA", "Code point ranges for which Python's `str.isalpha()` is true.", ranges(str.isalpha))
emit("WORD", "Code point ranges of Python's `\\w` (`str.isalnum()` or `_`).", ranges(lambda c: c.isalnum() or c == "_"))
